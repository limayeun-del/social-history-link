
import random

# 1. 사회 키워드별 역사적 사건 5개씩 저장
history = {
    "윤리": [
        "세계 인권 선언",
        "노예제 폐지 운동",
        "여성 참정권 운동",
        "뉘른베르크 재판",
        "홀로코스트"
    ],

    "정치": [
        "대한민국 임시 정부",
        "4.19 혁명",
        "5.18 민주화 운동",
        "6월 민주 항쟁",
        "황국 신민화 정책"
    ],

    "경제": [
        "산업 혁명",
        "세계 대공황",
        "새마을 운동",
        "IMF 외환 위기",
        "경제 개발 5개년 계획"
    ]
}


# 2. 역사적 사건 설명 함수
def get_information(event):

    if event == "세계 인권 선언":
        return "1948년 유엔에서 채택된 선언으로, 모든 인간의 기본적 권리와 자유를 보장하기 위한 것이다."

    elif event == "노예제 폐지 운동":
        return "인간을 소유하고 강제로 노동시키는 노예제를 없애기 위해 전개된 운동이다."

    elif event == "여성 참정권 운동":
        return "여성에게 투표권을 부여하고 정치 참여의 기회를 보장하기 위해 전개된 운동이다."

    elif event == "뉘른베르크 재판":
        return "제2차 세계 대전 이후 나치 독일의 전쟁 범죄와 반인도적 범죄를 처벌하기 위해 열린 재판이다."

    elif event == "홀로코스트":
        return "나치 독일이 제2차 세계 대전 중 유대인을 비롯한 여러 집단을 조직적으로 박해하고 학살한 사건이다."

    elif event == "대한민국 임시 정부":
        return "1919년 3·1 운동 이후 중국 상하이에서 수립된 독립운동 정부로, 한국의 독립을 위해 활동하였다."

    elif event == "4.19 혁명":
        return "1960년 이승만 정부의 부정 선거와 독재에 항의하여 학생과 시민들이 일으킨 민주화 운동이다."

    elif event == "5.18 민주화 운동":
        return "1980년 광주에서 신군부의 권력 장악과 민주화 억압에 저항하여 시민들이 전개한 민주화 운동이다."

    elif event == "6월 민주 항쟁":
        return "1987년 대통령 직선제 개헌과 민주화를 요구하며 전국적으로 전개된 시민들의 민주화 운동이다."

    elif event == "황국 신민화 정책":
        return "일제 강점기에 일본이 한국인을 일본 천황의 신민으로 만들기 위해 일본어 사용과 신사 참배 등을 강요한 정책이다."

    elif event == "산업 혁명":
        return "18세기 후반 영국에서 시작되어 기계와 공장 중심의 생산 방식으로 산업 구조가 변화한 사건이다."

    elif event == "세계 대공황":
        return "1929년 미국의 주가 폭락을 계기로 세계 경제가 큰 위기에 빠지고 실업과 빈곤이 확산된 사건이다."

    elif event == "새마을 운동":
        return "1970년대 농촌의 생활 환경 개선과 소득 증대를 목표로 추진된 지역 개발 운동이다."

    elif event == "IMF 외환 위기":
        return "1997년 한국에서 외화 부족으로 발생한 경제 위기로, 국제통화기금에 구제 금융을 요청하게 된 사건이다."

    elif event == "경제 개발 5개년 계획":
        return "1960년대부터 정부가 경제 성장을 위해 추진한 계획으로, 산업화와 수출 증대를 통해 경제 발전을 이루고자 하였다."

    else:
        return "사건을 검색할 수 없습니다."


# 3. 사회 키워드 입력받기
print("사회 키워드: 윤리, 정치, 경제")

society = input("알고 싶은 사회 키워드를 입력하세요: ")


# 4. 선택한 키워드에 해당하는 사건 3개 무작위 출력
if society in history:

    print("\n연관 역사적 사건 >>")

    # 해당 키워드의 사건 5개 중 3개 무작위 선택
    selected_history = random.sample(history[society], 3)

    # for문으로 선택된 사건 출력
    for event in selected_history:
        print(event)

    # 5. 더 알고 싶은 사건 입력받기
    history_exp = input(
        "\n더 알고 싶은 역사적 사건을 입력하세요: "
    )

    # 6. 선택된 사건인지 확인
    if history_exp in selected_history:

        print("\n역사적 사건 설명 >>")
        print(get_information(history_exp))

    else:
        print("사건을 검색할 수 없습니다.")

else:
    print("잘못된 사회 키워드입니다.")
